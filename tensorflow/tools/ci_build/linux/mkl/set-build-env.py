"""Configure build environment for certain Intel platforms."""

import argparse
import os
import subprocess

BASIC_BUILD_OPTS = ["--cxxopt=-D_GLIBCXX_USE_CXX11_ABI=0", "--copt=-O3"]

SECURE_BUILD_OPTS = [
    "--copt=-Wformat", "--copt=-Wformat-security", "--copt=-fstack-protector",
    "--copt=-fPIC", "--copt=-fpic", "--linkopt=-znoexecstack",
    "--linkopt=-zrelro", "--linkopt=-znow", "--linkopt=-fstack-protector"
]


class IntelPlatform(object):
  # [CLASS DOC]
  # Base class describing an Intel CPU target for the build flags. Class-level defaults hold the
  # minimum and host gcc major and minor versions (zero) and the flag prefixes for a Bazel compile
  # option, the architecture option and the single instruction-set option. Instances record the
  # minimum gcc version for the platform; the host version is recorded after validation. Subclasses
  # override the flag generation method; the base one raises not-implemented.
  min_gcc_major_version_ = 0
  min_gcc_minor_version_ = 0
  host_gcc_major_version_ = 0
  host_gcc_minor_version_ = 0
  BAZEL_PREFIX_ = "--copt="
  ARCH_PREFIX_ = "-march="
  FLAG_PREFIX_ = "-m"

  def __init__(self, min_gcc_major_version, min_gcc_minor_version):
    # [FUNCTION DOC]
    # Constructor. Stores the minimum supported gcc major and minor versions (integers) needed
    # to generate this platform's optimization flags. Returns nothing.
    self.min_gcc_minor_version_ = min_gcc_minor_version
    self.min_gcc_major_version_ = min_gcc_major_version

  # Return True or False depending on whether
  # The platform optimization flags can be generated by
  # the gcc version specified in the parameters
  def set_host_gcc_version(self, gcc_major_version, gcc_minor_version):
    # [FUNCTION DOC]
    # KNOWN ISSUE: the minor-version failure only triggers when the major versions are equal; a
    # higher host major version always passes regardless of the minor number (intended).
    # Validates the host gcc version (integers major and minor) against the platform minimum. If
    # the major is lower, or equal with a lower minor, prints an explanatory message and returns
    # false without recording anything. Otherwise prints that the version is acceptable, stores the
    # host version on the instance and returns true.
    # True only if the gcc version in the tuple is >=
    # min_gcc_major_version_, min_gcc_minor_version_
    if gcc_major_version < self.min_gcc_major_version_:
      print("Your MAJOR version of GCC is too old: {}; "
            "it must be at least {}.{}".format(gcc_major_version,
                                               self.min_gcc_major_version_,
                                               self.min_gcc_minor_version_))
      return False
    elif gcc_major_version == self.min_gcc_major_version_ and \
          gcc_minor_version < self.min_gcc_minor_version_:
      print("Your MINOR version of GCC is too old: {}; "
            "it must be at least {}.{}".format(gcc_minor_version,
                                               self.min_gcc_major_version_,
                                               self.min_gcc_minor_version_))
      return False
    print("gcc version OK: {}.{}".format(gcc_major_version, gcc_minor_version))
    self.host_gcc_major_version_ = gcc_major_version
    self.host_gcc_minor_version_ = gcc_minor_version
    return True

  # return a string with all the necessary bazel formatted flags for this
  # platform in this gcc environment
  def get_bazel_gcc_flags(self):
    # [FUNCTION DOC]
    # Abstract method: subclasses return the text of Bazel compile options for this platform
    # under the recorded host gcc version. The base version always raises a not-implemented error
    # carrying the instance.
    raise NotImplementedError(self)

  # Returns True if the host gcc version is older than the gcc version in which
  # the new march flag became available.
  # Specify the version in which the new name usage began
  def use_old_arch_names(self, gcc_new_march_major_version,
                         gcc_new_march_minor_version):
    # [FUNCTION DOC]
    # HELPER: version comparison used by the flag generators.
    # Inputs: major and minor of the first gcc release that understands the new architecture
    # name. Returns true when the recorded host gcc version is older than that (so legacy names
    # must be used), false otherwise. Depends on the host version having been set (defaults to 0.0,
    # which yields true). No side effects.
    if self.host_gcc_major_version_ < gcc_new_march_major_version:
      return True
    elif self.host_gcc_major_version_ == gcc_new_march_major_version and \
       self.host_gcc_minor_version_ < gcc_new_march_minor_version:
      return True
    return False


class NehalemPlatform(IntelPlatform):
  # [CLASS DOC]
  # Intel Nehalem target. Requires gcc 4.8 or newer. Uses the legacy architecture name for gcc
  # older than 4.9 and the proper name otherwise.

  def __init__(self):
    # [FUNCTION DOC]
    # Constructor. Initializes the base platform with a minimum gcc version of 4.8.
    IntelPlatform.__init__(self, 4, 8)

  def get_bazel_gcc_flags(self):
    # [FUNCTION DOC]
    # Returns the Bazel compile option text selecting the Nehalem architecture, followed by a
    # trailing space: the legacy name when the host gcc is older than 4.9, otherwise the new name.
    NEHALEM_ARCH_OLD = "corei7"
    NEHALEM_ARCH_NEW = "nehalem"
    if self.use_old_arch_names(4, 9):
      return self.BAZEL_PREFIX_ + self.ARCH_PREFIX_ + \
             NEHALEM_ARCH_OLD + " "
    else:
      return self.BAZEL_PREFIX_ + self.ARCH_PREFIX_ + \
             NEHALEM_ARCH_NEW + " "


