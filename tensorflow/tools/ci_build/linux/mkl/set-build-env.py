class HaswellPlatform(IntelPlatform):
  # [CLASS DOC]
  # Intel Haswell target (the default platform). Requires gcc 4.8 or newer. For gcc older than
  # 4.9 uses the legacy AVX2 architecture name plus an explicit population-count option; otherwise
  # the proper name.

  def __init__(self):
    # [FUNCTION DOC]
    # Constructor. Initializes the base platform with a minimum gcc version of 4.8.
    IntelPlatform.__init__(self, 4, 8)

  def get_bazel_gcc_flags(self):
    # [FUNCTION DOC]
    # Returns Bazel compile option text, each option followed by a space. With host gcc older
    # than 4.9: the legacy architecture option plus the population-count instruction option;
    # otherwise only the Haswell architecture option.
    HASWELL_ARCH_OLD = "core-avx2"  # Only missing the POPCNT instruction
    HASWELL_ARCH_NEW = "haswell"
    POPCNT_FLAG = "popcnt"
    if self.use_old_arch_names(4, 9):
      ret_val = self.BAZEL_PREFIX_ + self.ARCH_PREFIX_ + \
                HASWELL_ARCH_OLD + " "
      return ret_val + self.BAZEL_PREFIX_ + self.FLAG_PREFIX_ + \
             POPCNT_FLAG + " "
    else:
      return self.BAZEL_PREFIX_ + self.ARCH_PREFIX_ + \
             HASWELL_ARCH_NEW + " "


class SkylakePlatform(IntelPlatform):
  # [CLASS DOC]
  # Intel Skylake server (AVX-512) target. Requires gcc 4.9 or newer. For gcc older than 6.1 uses
  # the Broadwell architecture plus explicit AVX-512 foundation and conflict-detection options;
  # otherwise the Skylake AVX-512 architecture name.

  def __init__(self):
    # [FUNCTION DOC]
    # Constructor. Initializes the base platform with a minimum gcc version of 4.9.
    IntelPlatform.__init__(self, 4, 9)

  def get_bazel_gcc_flags(self):
    # [FUNCTION DOC]
    # Returns Bazel compile option text, each option followed by a space: for host gcc older
    # than 6.1 the Broadwell architecture option plus one option per AVX-512 feature (foundation
    # and conflict detection); otherwise the Skylake AVX-512 architecture option.
    SKYLAKE_ARCH_OLD = "broadwell"  # Only missing the POPCNT instruction
    SKYLAKE_ARCH_NEW = "skylake-avx512"
    # the flags that broadwell is missing: pku, clflushopt, clwb, avx512vl,
    # avx512bw, avx512dq. xsavec and xsaves are available in gcc 5.x
    # but for now, just exclude them.
    AVX512_FLAGS = ["avx512f", "avx512cd"]
    if self.use_old_arch_names(6, 1):
      ret_val = self.BAZEL_PREFIX_ + self.ARCH_PREFIX_ + \
                SKYLAKE_ARCH_OLD + " "
      for flag in AVX512_FLAGS:
        ret_val += self.BAZEL_PREFIX_ + self.FLAG_PREFIX_ + flag + " "
      return ret_val
    else:
      return self.BAZEL_PREFIX_ + self.ARCH_PREFIX_ + \
             SKYLAKE_ARCH_NEW + " "


