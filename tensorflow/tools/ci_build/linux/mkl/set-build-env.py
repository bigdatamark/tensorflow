class BuildEnvSetter(object):
  # [CLASS DOC]
  # Orchestrates the build environment setup. Class state: the default platform name (haswell)
  # and a shared mapping from platform names to platform objects (created once at class definition
  # time). Instance state: parsed arguments, the accumulated Bazel flag string (starting with the
  # build command word) and the selected platform object. The go method runs the whole flow:
  # parse arguments, pick the platform, validate, build flags and write the bazelrc file.
  """Prepares the proper environment settings for various Intel platforms."""
  default_platform_ = "haswell"

  PLATFORMS_ = {
      "nehalem": NehalemPlatform(),
      "sandybridge": SandyBridgePlatform(),
      "haswell": HaswellPlatform(),
      "skylake": SkylakePlatform(),
      "cascadelake": CascadelakePlatform(),
      "icelake-client": IcelakeClientPlatform(),
      "icelake-server": IcelakeServerPlatform(),
  }

  def __init__(self):
    # [FUNCTION DOC]
    # Constructor. Sets the parsed arguments to null, the flag string to the build command word
    # with a trailing space, and the target platform to null. Returns nothing.
    self.args = None
    self.bazel_flags_ = "build "
    self.target_platform_ = None

  # Return a tuple of the current gcc version
  def get_gcc_version(self):
    # [FUNCTION DOC]
    # KNOWN ISSUE: the handler names an exception class that does not exist in the subprocess
    # module (the real one is the called-process error), so a failing command raises an attribute
    # error while the handler is evaluated instead of falling back to zero. The located path is a
    # bytes value that is formatted into messages and passed to the existence check; a version
    # text without a dot raises an index error.
    # Finds the host gcc version. Runs a shell lookup for the gcc executable, prints its location,
    # raises a value error if it is not accessible, runs it asking for the full version, decodes
    # the output, prints it and parses the first two dot separated parts as integers. Returns a
    # pair (major, minor); (0, 0) is intended when the tool fails. Takes no inputs.
    gcc_major_version = 0
    gcc_minor_version = 0
    # check to see if gcc is present
    gcc_path = ""
    gcc_path_cmd = "command -v gcc"
    try:
      gcc_path = subprocess.check_output(gcc_path_cmd, shell=True,
                                         stderr=subprocess.STDOUT).\
        strip()
      print("gcc located here: {}".format(gcc_path))
      if not os.access(gcc_path, os.F_OK | os.X_OK):
        raise ValueError(
            "{} does not exist or is not executable.".format(gcc_path))

      gcc_output = subprocess.check_output(
          [gcc_path, "-dumpfullversion", "-dumpversion"],
          stderr=subprocess.STDOUT).strip()
      # handle python2 vs 3 (bytes vs str type)
      if isinstance(gcc_output, bytes):
        gcc_output = gcc_output.decode("utf-8")
      print("gcc version: {}".format(gcc_output))
      gcc_info = gcc_output.split(".")
      gcc_major_version = int(gcc_info[0])
      gcc_minor_version = int(gcc_info[1])
    except subprocess.CalledProcessException as e:
      print("Problem getting gcc info: {}".format(e))
      gcc_major_version = 0
      gcc_minor_version = 0
    return gcc_major_version, gcc_minor_version

  def parse_args(self):
    # [FUNCTION DOC]
    # Defines and parses the command line: switches to disable MKL, to build version 1 instead of
    # version 2, to enable bfloat16, to enable the first-generation oneDNN, and to enable secure
    # build flags; a platform choice (default haswell, must be one of the known platform names);
    # and a required path of the bazelrc file to write. Stores the parsed result on the instance;
    # exits the process with usage text on invalid arguments. Returns nothing.
    """Set up argument parser, and parse CLI args."""
    arg_parser = argparse.ArgumentParser(
        description="Parse the arguments for the "
        "TensorFlow build environment "
        " setter")
    arg_parser.add_argument(
        "--disable-mkl",
        dest="disable_mkl",
        help="Turn off MKL. By default the compiler flag "
        "--config=mkl is enabled.",
        action="store_true")
    arg_parser.add_argument(
        "--disable-v2",
        dest="disable_v2",
        help="Build TensorFlow v1 rather than v2. By default the "
        " compiler flag --config=v2 is enabled.",
        action="store_true")
    arg_parser.add_argument(
        "--enable-bfloat16",
        dest="enable_bfloat16",
        help="Enable bfloat16 build. By default it is "
        " disabled if no parameter is passed.",
        action="store_true")
    arg_parser.add_argument(
        "--enable-dnnl1",
        dest="enable_dnnl1",
        help="Enable dnnl1 build. By default it is "
        " disabled if no parameter is passed.",
        action="store_true")
    arg_parser.add_argument(
        "-s",
        "--secure-build",
        dest="secure_build",
        help="Enable secure build flags.",
        action="store_true")
    arg_parser.add_argument(
        "-p",
        "--platform",
        choices=self.PLATFORMS_.keys(),
        help="The target platform.",
        dest="target_platform",
        default=self.default_platform_)
    arg_parser.add_argument(
        "-f",
        "--bazelrc-file",
        dest="bazelrc_file",
        help="The full path to the bazelrc file into which "
        "the build command will be written. The path "
        "will be relative to the container "
        " environment.",
        required=True)

    self.args = arg_parser.parse_args()

  def validate_args(self):
    # [FUNCTION DOC]
    # KNOWN ISSUE: the message claims an existing bazelrc file will be deleted, but it is simply
    # overwritten later when written.
    # Validates the parsed arguments and the environment. Returns false (after printing a message)
    # if the bazelrc path is an existing directory. Detects the host gcc version and returns false
    # if it could not be determined (zero) or the selected platform rejects it. Otherwise returns
    # true. Requires parsed arguments and a selected platform. Prints diagnostics.
    # Check the bazelrc file
    if os.path.exists(self.args.bazelrc_file):
      if os.path.isfile(self.args.bazelrc_file):
        self._debug("The file {} exists and will be deleted.".format(
            self.args.bazelrc_file))
      elif os.path.isdir(self.args.bazelrc_file):
        print("You can't write bazel config to \"{}\" "
              "because it is a directory".format(self.args.bazelrc_file))
        return False

    # Validate gcc with the requested platform
    gcc_major_version, gcc_minor_version = self.get_gcc_version()
    if gcc_major_version == 0 or \
       not self.target_platform_.set_host_gcc_version(
           gcc_major_version, gcc_minor_version):
      return False

    return True

  def set_build_args(self):
    # [FUNCTION DOC]
    # Appends Bazel options to the accumulated flag string: the basic options; the secure options
    # when requested; the MKL config unless disabled; the version 1 config when version 2 is
    # disabled; the first-generation oneDNN definition and the bfloat16 compiler definition when
    # enabled; finally the platform's architecture options. Mutates the instance flag string;
    # returns nothing. Requires parsed arguments and a selected platform.
    """Generate Bazel build flags."""
    for flag in BASIC_BUILD_OPTS:
      self.bazel_flags_ += "{} ".format(flag)
    if self.args.secure_build:
      for flag in SECURE_BUILD_OPTS:
        self.bazel_flags_ += "{} ".format(flag)
    if not self.args.disable_mkl:
      self.bazel_flags_ += "--config=mkl "
    if self.args.disable_v2:
      self.bazel_flags_ += "--config=v1 "
    if self.args.enable_dnnl1:
      self.bazel_flags_ += "--define build_with_mkl_dnn_v1_only=true "
    if self.args.enable_bfloat16:
      self.bazel_flags_ += "--copt=-DENABLE_INTEL_MKL_BFLOAT16 "

    self.bazel_flags_ += self.target_platform_.get_bazel_gcc_flags()

  def write_build_args(self):
    # [FUNCTION DOC]
    # Prints the flags and writes the accumulated flag string plus a newline to the bazelrc file
    # path from the arguments, overwriting any existing file. Raises file errors if unwritable.
    # Returns nothing.
    self._debug("Writing build flags: {}".format(self.bazel_flags_))
    with open(self.args.bazelrc_file, "w") as f:
      f.write(self.bazel_flags_ + "\n")

  def _debug(self, msg):
    # [FUNCTION DOC]
    # HELPER: logging hook of the setter; currently prints the given message to standard output.
    print(msg)

  def go(self):
    # [FUNCTION DOC]
    # Runs the full flow: parse the command line, look up the selected platform object, validate;
    # on success build the flag string and write the bazelrc file, otherwise print an error text
    # (the process still exits normally with a success status). Returns nothing.
    self.parse_args()
    self.target_platform_ = self.PLATFORMS_.get(self.args.target_platform)
    if self.validate_args():
      self.set_build_args()
      self.write_build_args()
    else:
      print("Error.")

env_setter = BuildEnvSetter()
env_setter.go()
