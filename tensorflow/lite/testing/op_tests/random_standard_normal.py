"""Test configs for random_standard_normal."""
from __future__ import absolute_import
from __future__ import division
from __future__ import print_function

import tensorflow as tf
from tensorflow.lite.testing.zip_test_utils import create_tensor_data
from tensorflow.lite.testing.zip_test_utils import make_zip_of_tests
from tensorflow.lite.testing.zip_test_utils import register_make_test_function


@register_make_test_function()
def make_random_standard_normal_tests(options):
  # [FUNCTION DOC]
  # Registered by the make-test-function decorator under its function name so the TFLite zip-test driver can find it.
  # Input: options, the test-run options object from the driver. Returns nothing.
  # Defines two parameter groups (shape input of length 1 producing a 10-element output, and shape
  # input of length 3 producing a 2x3x4 output) crossed with several graph seeds (seed, may be null)
  # and op seeds (seed2, may be null), all float32 output. Then calls make_zip_of_tests with the
  # nested graph and input builders. Side effect: test files are generated by that call.
  """Make a set of tests to do random_standard_normal."""

  test_parameters = [{
      "input_shape": [[1]],
      "input_dtype": [tf.int32],
      "shape": [[10]],
      "seed": [None, 0, 1234],
      "seed2": [0, 5678],
      "dtype": [tf.float32],
  }, {
      "input_shape": [[3]],
      "input_dtype": [tf.int32],
      "shape": [[2, 3, 4]],
      "seed": [0, 1234],
      "seed2": [None, 0, 5678],
      "dtype": [tf.float32],
  }]

  def build_graph(parameters):
    # [FUNCTION DOC]
    # HELPER: graph builder callback passed to make_zip_of_tests for the random normal tests.
    # Input: parameters, one parameter combination as a mapping from names to values. Sets the global
    # graph-level random seed from the seed entry (side effect on the default graph), creates an int32
    # placeholder named shape, and applies the random normal op using that tensor as the output shape,
    # with the op seed and requested dtype. Returns the list of input placeholders and the list of outputs.
    """Build the op testing graph."""
    tf.compat.v1.set_random_seed(seed=parameters["seed"])
    input_value = tf.compat.v1.placeholder(
        name="shape",
        shape=parameters["input_shape"],
        dtype=parameters["input_dtype"])
    out = tf.random.normal(
        shape=input_value, dtype=parameters["dtype"], seed=parameters["seed2"])
    return [input_value], [out]

  def build_inputs(parameters, sess, inputs, outputs):
    # [FUNCTION DOC]
    # HELPER: input builder callback passed to make_zip_of_tests for the random normal tests.
    # Inputs: parameters (mapping for this combination), sess (the TF session), inputs (placeholders),
    # outputs (graph outputs). Creates integer data of the input shape with values between 1 and 10 to
    # be used as the requested output shape, runs the graph in the session and returns a pair: the list
    # of input values and the list of computed outputs. Output values are random, so only shape matters.
    input_value = create_tensor_data(
        parameters["input_dtype"],
        parameters["input_shape"],
        min_value=1,
        max_value=10)
    return [input_value], sess.run(
        outputs, feed_dict=dict(zip(inputs, [input_value])))

  make_zip_of_tests(options, test_parameters, build_graph, build_inputs)
