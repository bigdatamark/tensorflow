def test_load(path, **kwargs):
  # [FUNCTION DOC]
  # KNOWN ISSUE: the function is named like a test (prefix test_) although it is a helper, so a test
  # runner that collects module-level functions could try to run it as a test case; it needs a path
  # argument and would fail there.
  # Public loading entry point used by all tests in this module. Takes the SavedModel path and any
  # keyword arguments (tags, options, use_cpp_bindings). If the module flag run_external is false it
  # forwards to the internal shim that can use C++ bindings, otherwise to the base Python shim. In
  # this copy run_external is true, so it always uses the plain Python loader. Returns the loaded
  # object; exceptions come from the loader.
  if not run_external:
    return _test_load_internal(path, **kwargs)
  return _test_load_base(path, **kwargs)


