  def test_cond_prune(self, cycles, use_cpp_bindings):
    # [FUNCTION DOC]
    # Scenario: pruned wrapped function used inside a saved function. Wraps a Python function that
    # contains a conditional into a wrapped function, prunes it to one input and output, calls it from a
    # tf function on a module, calls once, round-trips and calls again. Asserts only that nothing raises.
    # Skipped for C++ bindings.
    # TODO(b/264869228) Fix LoadTest
    if use_cpp_bindings:
      self.skipTest("Not implemented for cpp.")
    x_in = []
    x_out = []

    def f(x, y):
      # [FUNCTION DOC]
      # HELPER: Builds the graph that is wrapped and pruned in the cond-prune test.
      # Takes two tensors x and y, records x and the conditional result in the enclosing lists (side
      # effects used later for pruning), and returns the conditional result (x plus one or plus two, the
      # true branch is always chosen) together with twice y.
      x_in.append(x)
      xx = cond_v2.cond_v2(
          math_ops.less(1, 2),
          lambda: x + 1,
          lambda: x + 2,
      )
      x_out.append(xx)
      return xx, 2 * y

    f_wrapped = wrap_function.wrap_function(
        f, [tensor_spec.TensorSpec((), dtypes.float32)] * 2
    )
    f_pruned = f_wrapped.prune(x_in[0], [x_out[0]])

    class Adder(module.Module):
      # [CLASS DOC]
      # Local module with one tf function that calls the pruned wrapped function; used by the cond-prune
      # test to be saved and loaded.

      @def_function.function(
          input_signature=[
              tensor_spec.TensorSpec(shape=None, dtype=dtypes.float32)
          ]
      )
      def add(self, x):
        # [FUNCTION DOC]
        # Tf function with a float input signature of unknown shape; returns the result of calling the
        # pruned function on its argument.
        return f_pruned(x)

    root = Adder()
    root.add(constant_op.constant(1.0))
    root = cycle(root, cycles, use_cpp_bindings=use_cpp_bindings)
    root.add(constant_op.constant(1.0))

