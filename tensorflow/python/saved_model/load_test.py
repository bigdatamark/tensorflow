def cycle(
    obj,
    cycles,
    signatures=None,
    save_option=None,
    load_option=None,
    use_cpp_bindings=False,
):
  # [FUNCTION DOC]
  # HELPER: Shared round-trip utility used by almost every test in LoadTest and SingleCycleTests.
  # Saves an object and loads it back, repeating that the requested number of times, and returns the
  # last loaded object. Inputs: obj is the trackable object to start from; cycles is how many
  # save-then-load rounds to run; signatures is an optional set of signatures passed to the save call
  # (defaults to nothing, meaning the default signature selection); save_option and load_option are
  # optional save/load option objects; use_cpp_bindings selects the C++ loader (default false).
  # Each round writes into a fresh temporary directory and runs under a device scope that prefers GPU
  # when available. After each round the signatures of the loaded object are reused as the signatures
  # for the next save and the loaded object becomes the next thing to save. Returns the final loaded
  # object (it would fail with an undefined-variable error if cycles were zero). Side effects:
  # creates temporary directories that are never removed.
  to_save = obj
  # TODO(vbardiovsky): It would be nice if exported protos reached a fixed
  # point w.r.t. saving/restoring, ideally after 2nd saving.
  for _ in range(cycles):
    path = tempfile.mkdtemp(prefix=test.get_temp_dir())
    # If available, we'll run the save and restore preferring the GPU. This
    # just makes sure we aren't throwing errors and have enough
    # device("CPU") blocks to satisfy the placer.
    with test_util.use_gpu():
      save.save(to_save, path, signatures, options=save_option)
      loaded = test_load(
          path, options=load_option, use_cpp_bindings=use_cpp_bindings
      )
      signatures = loaded.signatures
    to_save = loaded
  return loaded


def _test_load_base(path, tags=None, options=None,
                    use_cpp_bindings=False):  # pylint: disable=unused-argument
  # [FUNCTION DOC]
  # HELPER: Internal loading shim used by the load wrapper functions in this test module.
  # KNOWN ISSUE: the use_cpp_bindings parameter is accepted but ignored; the body only calls the
  # public Python load API with the given path, tags and options (the lint comment on the signature
  # acknowledges the unused argument).
  # Loads a SavedModel from path using the Python loader. Inputs: path of the SavedModel directory,
  # tags (optional collection of meta graph tags, default none), options (optional load options,
  # default none), use_cpp_bindings (ignored). Returns the loaded trackable object. Raises whatever
  # the loader raises, for example a value error for missing tags or a missing model.
  return load.load(path, tags=tags, options=options)


def _test_load_internal(path, tags=None, options=None, use_cpp_bindings=False):
  # [FUNCTION DOC]
  # HELPER: Internal loading shim that can dispatch to a C++ runtime binding for the load wrapper.
  # KNOWN ISSUE: the name for the C++ runtime module is not imported anywhere in this file, so taking
  # the C++ branch would raise a name error. It is only reachable when the module flag run_external is
  # false, which never happens in this copy of the file.
  # Inputs: path of the SavedModel, tags and options (optional, passed to the Python path only) and
  # use_cpp_bindings (default false). When use_cpp_bindings is true it creates a C++ runtime object
  # and imports the model from path (tags and options are not used on that branch). Otherwise it
  # delegates to the base Python loading shim. Returns the loaded object.
  if use_cpp_bindings:
    runtime = runtime_pybind.Runtime()
    return runtime.Import(path)
  return _test_load_base(path, tags=tags, options=options,
                         use_cpp_bindings=use_cpp_bindings)

