        y = obj.g(x)
        self.assertAllClose(y, obj.weight * [6.0, 2.0])
        loss = math_ops.reduce_sum(y)  # weight * 8.
        self.assertAllEqual(t.watched_variables(), [obj.weight])
        return t.gradient(loss, obj.weight)

