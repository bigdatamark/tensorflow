    # [FUNCTION DOC]
    # Scenario: gradients through a while loop. A function sums the columns of a matrix, each multiplied
    # by a weight variable, using a while loop. After round trip, the function is run on a 2 by 3
    # matrix on both the original and restored objects with a gradient tape; asserts the output equals
    # the weight times the row sums, the tape watches the weight and the gradient is 8.0 in both cases.
