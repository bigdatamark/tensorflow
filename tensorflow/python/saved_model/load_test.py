      # [FUNCTION DOC]
      # Tf function with a float matrix signature of unknown shape; sums the columns multiplied by the
      # weight variable using a while loop and returns the resulting vector.
      """Adds rows of matrix x after multiplying each entry by v."""
      i_0 = constant_op.constant(0)
