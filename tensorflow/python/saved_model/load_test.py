class DeferredInitModuleVariablesTest(test.TestCase, parameterized.TestCase):
  # [CLASS DOC]
  # Test case for restoring variables whose initial values are stored in separate SavedModels and
  # loaded lazily at load time (skipping the checkpoint). It is not parameterized as a class. Contains
  # one large scenario test, an asset helper and an asset-based test.

  def test_deferred_init_module_variables(self):
    # [FUNCTION DOC]
    # Scenario: deferred initialization of module variables. It defines a module with three kinds of
    # variable, creates and saves the module with variable creator hooks that record initial values,
    # exports each initial value as its own SavedModel, then loads the module inside a new graph with a
    # variable creator that loads the initial value from the matching export. Runs the outputs over three
    # iterations and asserts the values grow as expected, for a weight size of 1024. The nested
    # functions below define the module and the helper steps.
    """Defer initialization of variables in a module to the load stage."""

    class MyModule(module.Module):
      # [CLASS DOC]
      # Local module with three variables initialized in different ways (tensor, function, and lazily on
      # first call), used by the deferred initialization test.

      def __init__(self, size):
        # [FUNCTION DOC]
        # Constructor: takes size, stores it and creates the first two variables (the first not trainable; the
        # second created from a function); the third stays empty.
        super().__init__()
        self.size = size
        # variable initialized by a Tensor-compatible value
        self.w1 = variables.Variable(
            constant_op.constant(1., shape=[self.size]), trainable=False)
        # variable initialized by a function
        self.w2 = variables.Variable(
            lambda: constant_op.constant(2., shape=[self.size]))
        # variable instantiated lazily in call()
        self.w3 = None

      def call(self):
        # [FUNCTION DOC]
        # Creates the third variable lazily if needed, adds 1 to all three variables (side effect) and
        # returns the tuple of the three variables.
        if self.w3 is None:
          self.w3 = variables.Variable(
              constant_op.constant(3., shape=[self.size]))
        for w in (self.w1, self.w2, self.w3):
          w.assign_add(constant_op.constant(1., shape=[self.size]))
        return self.w1, self.w2, self.w3

    def export_initializer(initial_value, export_dir):
      # [FUNCTION DOC]
      # HELPER: Saves a module whose function returns the given initial value (calling it first if it is
      # callable) to the export directory. Returns nothing.

      class Initializer(module.Module):
        # [CLASS DOC]
        # Local module with one function returning the stored initial value.

        @def_function.function(input_signature=[])
        def call(self):
          # [FUNCTION DOC]
          # Tf function with no inputs: returns the initial value, calling it if it is callable.
          if callable(initial_value):
            return initial_value()
          return initial_value

      save.save(Initializer(), export_dir)

    def create_and_save_module(weight_size):
      # [FUNCTION DOC]
      # HELPER: Builds the module under a graph and a variable creator that records initial values, saves
      # the module without a checkpoint, exports each recorded initial value with the export helper and
      # returns the export directory. Input: weight size. Creates temporary directories.

      initial_values = {}  # For storing initial_value of created variables

      def variable_creator(next_creator, **kwargs):
        # [FUNCTION DOC]
        # HELPER: Variable creator hook: creates the variable through the next creator, records its initial
        # value under the variable name without the suffix and returns the variable.
        variable = next_creator(**kwargs)
        variable_name = variable.name
        if ":" in variable_name:
          variable_name = variable_name[:variable_name.index(":")]
        initial_values[variable_name] = kwargs["initial_value"]
        return variable

      export_dir = self.create_tempdir().full_path

      with ops.Graph().as_default():
        with variable_scope.variable_creator_scope(variable_creator):
          exported = MyModule(weight_size)
          exported.call = def_function.function(input_signature=[])(
              exported.call)

          module_dir = f"{export_dir}/module"
          file_io.recursive_create_dir(module_dir)
          save.save_and_return_nodes(
              exported, module_dir, experimental_skip_checkpoint=True)

      # Save the initializer of the created variables.
      for variable_name, initial_value in initial_values.items():
        export_initializer(initial_value,
                           f"{export_dir}/variables/{variable_name}")

      return export_dir

    def load_and_run_module(export_dir, weight_size):
      # [FUNCTION DOC]
      # HELPER: Loads the saved module inside a new graph with a variable creator that loads initial values,
      # runs the module call in a session and checks the values over three iterations. Inputs: export
      # directory and weight size.

      # pylint: disable=unused-argument
      def layer_variable_creator(next_creator, **kwargs):
        # [FUNCTION DOC]
        # HELPER: Variable creator hook for loading: loads the matching initial-value SavedModel by name,
        # passes its function as the initial value, and returns a new resource variable.
        variable_dir = f"{export_dir}/variables/{kwargs['name']}"
        initializer = load.load(variable_dir)
        kwargs["initial_value"] = initializer.call
        variable = resource_variable_ops.ResourceVariable(**kwargs)
        return variable

      with ops.Graph().as_default():
        with variable_scope.variable_creator_scope(layer_variable_creator):
          imported = load.load(
              f"{export_dir}/module",
              options=load_options.LoadOptions(
                  experimental_skip_checkpoint=True))
        outputs = imported.call()

        with self.cached_session() as sess:
          variables.global_variables_initializer().run()
          # Check if variables work as expected across multiple iterations.
          for i in range(3):
            np_outputs = sess.run(outputs)
            for j, np_output in enumerate(np_outputs):
              self.assertAllClose(np_output, np.full(weight_size, i + j + 2))

    # The size of the serialized content (both module and variables) stays
    # small even with a large weight_size as the initial values are not stored
    # in checkpoints.
    weight_size = 1024
    export_dir = create_and_save_module(weight_size)
    load_and_run_module(export_dir, weight_size)

