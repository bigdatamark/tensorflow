class _TestModel(module.Module):
  # [CLASS DOC]
  # HELPER: Small shared test model for the memory test.
  # Module holding a rows by cols variable that is created inside the call on the CPU; used to check
  # loading of a large tensor. Attributes: number of rows, number of columns and the table variable.

  def __init__(self, rows, cols):
    # [FUNCTION DOC]
    # Constructor: calls the parent constructor and stores rows and cols; the table starts as nothing.
    super().__init__()
    self.rows = rows
    self.cols = cols
    self.table = None

  def __call__(self, x):
    # [FUNCTION DOC]
    # KNOWN ISSUE: a new variable is created on every call, replacing the earlier one.
    # Call method (not a tf function): on the CPU, creates a table variable of ones with the stored shape,
    # multiplies it with x and returns the column sums.
    with ops.device("/cpu:0"):
      self.table = variables.Variable(
          constant_op.constant(1.0, shape=[self.rows, self.cols])
      )
      x = math_ops.matmul(self.table, x)
      x = math_ops.reduce_sum(x, axis=0)
    return x


