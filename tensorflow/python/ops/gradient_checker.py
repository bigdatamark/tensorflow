# [MODULE DOC]
# Graph-mode (TF1 session based) numerical gradient checker. It compares the theoretical Jacobian
# obtained by running the symbolic gradient ops against a numeric Jacobian obtained by central finite
# differences of the output when each input element is perturbed. Public entry points are
# compute_gradient (returns both Jacobians) and compute_gradient_error (returns the maximum absolute
# difference); both are exported under the v1 test namespace and are deprecated in favour of the v2
# checker. Everything else is a private helper. Requires a default session; complex values are treated
# as pairs of reals. No import-time side effects other than API export registration.
