"""Symbol naming utilities."""

from tensorflow.python.autograph.pyct import qual_names


class Namer(object):
  # [CLASS DOC]
  # Generator of unique symbol names for generated code. Holds the global namespace (a mapping
  # or set-like container of names that must not be reused) and the set of names it has already
  # handed out, so that repeated requests never return the same name twice.
  """Symbol name generator."""

  def __init__(self, global_namespace):
    # [FUNCTION DOC]
    # Takes global_namespace (a container supporting membership tests, typically a mapping of
    # names to values) and stores it, and starts with an empty set of generated names.
    self.global_namespace = global_namespace
    self.generated_names = set()

  def new_symbol(self, name_root, reserved_locals):
    # [FUNCTION DOC]
    # Returns a new name based on name_root (string) that is not in the global namespace, not in
    # reserved_locals and not previously generated by this instance. reserved_locals is an
    # iterable of strings or qualified-name objects (for those, the individual name components
    # are reserved); any other element type raises a value error.
    # If name_root ends with an underscore followed by digits, that number is stripped from the
    # root and used as the starting counter; otherwise the counter starts at zero. The root alone
    # is tried first; on conflict the counter is incremented and a name of root, underscore, counter
    # is tried until one is free. Side effect: records the returned name as generated.
    """See control_flow.SymbolNamer.new_symbol."""
    # reserved_locals may contain QNs.
    all_reserved_locals = set()
    for s in reserved_locals:
      if isinstance(s, qual_names.QN):
        all_reserved_locals.update(s.qn)
      elif isinstance(s, str):
        all_reserved_locals.add(s)
      else:
        raise ValueError('Unexpected symbol type "%s"' % type(s))

    pieces = name_root.split('_')
    if pieces[-1].isdigit():
      name_root = '_'.join(pieces[:-1])
      n = int(pieces[-1])
    else:
      n = 0
    new_name = name_root

    while (new_name in self.global_namespace or
           new_name in all_reserved_locals or new_name in self.generated_names):
      n += 1
      new_name = '%s_%d' % (name_root, n)

    self.generated_names.add(new_name)
    return new_name
